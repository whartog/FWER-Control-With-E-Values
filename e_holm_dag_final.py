def run_dag_both_budgets(n_replications=N_REPLICATIONS_DAG):
    results = {}
    for budget in DAG_BUDGETS:
        times = np.zeros((n_replications, len(MU_ALTS_DAG), 3))
        rates = np.zeros((n_replications, len(MU_ALTS_DAG), 3, 2))
