# Compute B_20^{-1}(0.05) by discretizing the full Pareto-sum convolution recursion.
from scipy.signal import fftconvolve
from scipy.optimize import brentq

def calibrated_alpha_for_k(k, target_alpha=0.05, h=0.005):
    n_bins = int(np.ceil((k * (1 / 0.03 - 1) + 2) / h)) + 2
    edges = np.arange(n_bins + 1) * h
    kernel = 1 / (1 + edges[:-1]) - 1 / (1 + edges[1:])
    mass = kernel.copy()
    for _ in range(2, k + 1):
        mass = np.maximum(fftconvolve(mass, kernel)[:n_bins], 0)
    tail = 1 - np.r_[0, np.cumsum(mass)]
    def bound(a):
        z = (k/a-k)/h-k/2
        idx = int(np.floor(z))
        frac = z-idx
        return (1-frac)*tail[idx] + frac*tail[idx+1]
    return brentq(lambda a: bound(a) - target_alpha, 0.03, target_alpha, xtol=1e-12)

ALPHA_PRIME_20 = calibrated_alpha_for_k(20)
print(f"alpha'_20(0.05) = {ALPHA_PRIME_20:.8f}")

def run_processes(n = 20, n_1 = 5, mu_1 = 0.5, alpha = 0.05, max_steps = 100, seed = 0):
  T_p = float('inf')
  T_ep = float('inf')
  T_e = float('inf')

  n_0 = n - n_1

  e_processes = np.ones(n)
  maxima = np.ones(n)

  FWER_powers = np.zeros((5, 2))

  np.random.seed(seed)
  for t in range(max_steps):
    alts = np.random.normal(mu_1, 1, size = n_1)
    nulls = np.random.normal(0, 1, size = n_0)
    e_processes[:n_1] = e_processes[:n_1] * np.exp(mu_1 * alts - 0.5 * mu_1 ** 2)
    e_processes[n_1:] = e_processes[n_1:] * np.exp(mu_1 * nulls - 0.5 * mu_1 ** 2)
    maxima = np.maximum(maxima, e_processes)

    if T_p == float('inf'):
      best_p = np.min(p_holm(1/maxima))
      if best_p <= alpha:
        T_p = t+1

    if T_ep == float('inf'):
      best_ep = np.min(p_holm(1/e_processes))
      if best_ep <= alpha:
        T_ep = t+1

    if T_e == float('inf'):
      best_e = np.max(e_holm(e_processes))
      if best_e >= 1/alpha:
        T_e = t+1

  Ts = np.array([T_p, T_e, T_ep])


  adj_pvals = p_holm(1/maxima)
  FWER_powers[0,0] = np.any(adj_pvals[n_1:] <= alpha)
  FWER_powers[0,1] = np.mean(adj_pvals[:n_1] <= alpha)

  adj_evals = e_holm(e_processes)
  FWER_powers[1,0] = np.any(adj_evals[n_1:] >= 1/alpha)
  FWER_powers[1,1] = np.mean(adj_evals[:n_1] >= 1/alpha)

  adj_epvals = p_holm(1/e_processes)
  FWER_powers[2,0] = np.any(adj_epvals[n_1:] <= alpha)
  FWER_powers[2,1] = np.mean(adj_epvals[:n_1] <= alpha)

  alpha_prime = ALPHA_PRIME_20
  adj_pseudo_evals = e_holm(maxima)
  FWER_powers[3,0] = np.any(adj_pseudo_evals[n_1:] >= 1/alpha)
  FWER_powers[3,1] = np.mean(adj_pseudo_evals[:n_1] >= 1/alpha)
  FWER_powers[4,0] = np.any(adj_pseudo_evals[n_1:] >= 1/alpha_prime)
  FWER_powers[4,1] = np.mean(adj_pseudo_evals[:n_1] >= 1/alpha_prime)

  return Ts, FWER_powers

