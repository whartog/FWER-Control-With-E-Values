def e_dag(evals, budget = 'primary'):
  # ignore three-way interaction
  adj_evals = np.zeros(7)
  for i in range(3):
    adj_evals[i] = evals[i] / 3
  adj_evals[3] = min((evals[0] + evals[1]) / 3, (evals[0] + evals[3] / 2) / 3, (evals[1] + evals[3] / 2) / 3, evals[3] / 3)
  adj_evals[4] = min((evals[0] + evals[2]) / 3, (evals[0] + evals[4] / 2) / 3, (evals[2] + evals[4] / 2) / 3, evals[4] / 3)
  adj_evals[5] = min((evals[1] + evals[2]) / 3, (evals[1] + evals[5] / 2) / 3, (evals[2] + evals[5] / 2) / 3, evals[5] / 3)
  adj_evals[6] = 1
  return adj_evals

def p_dag(pvals, budget = 'primary'):
  adj_pvals = np.zeros(7)
  for i in range(3):
    adj_pvals[i] = pvals[i] * 3
  adj_pvals[3] = max(min(pvals[0], pvals[1]) * 3, 3 * pvals[3], min(pvals[0], 2 * pvals[3]) * 3, min(pvals[1], 2 * pvals[3]) * 3)
  adj_pvals[4] = max(min(pvals[0], pvals[2]) * 3, 3 * pvals[4], min(pvals[0], 2 * pvals[4]) * 3, min(pvals[2], 2 * pvals[4]) * 3)
  adj_pvals[5] = max(min(pvals[1], pvals[2]) * 3, 3 * pvals[5], min(pvals[1], 2 * pvals[5]) * 3, min(pvals[2], 2 * pvals[5]) * 3)
  adj_pvals[6] = 1
  return adj_pvals

# Section 8.3: num_votes independent ratings are averaged per caption-selection round.
# Also initialize every caption with a batch of num_votes ratings.
def run_bandits_balanced(num_per_arm, num_steps, seed = 0, arm_seed = 0, checkpoints = None, lam = 0.04, num_votes = 100):
  if not isinstance(num_votes, (int, np.integer)) or num_votes < 1:
    raise ValueError("num_votes must be a positive integer")
  np.random.seed(arm_seed)
  indices = []
  for a in range(8):
    a_indices = np.random.choice(df[df['type'] == a].index, num_per_arm)
    indices.extend(a_indices)

  num_iter = num_steps
  epsilon = 0.4
  mu_0 = 0.25
  alpha = 0.05

  df_indices = df.iloc[indices].reset_index()
  n_arms = len(indices)

  type_means = df_indices.groupby('type').agg({'mean':'mean'})
  betas = beta_contrasts @ type_means

  df_sim = pd.DataFrame(columns = ['pulls', 'averages', 'ucbs', 'type'])


  df_sim.pulls = np.ones(n_arms)
  df_sim.averages = np.array([
    np.random.choice([0, 0.5, 1], size=num_votes,
                     p=df_indices[['p1','p2','p3']].iloc[i]).mean()
    for i in range(n_arms)
  ])
  df_sim.ucbs = np.array([ucb(num_votes * df_sim.loc[i, 'pulls'], df_sim.loc[i, 'averages']) for i in range(n_arms)])
  df_sim['type'] = df_indices['type']

  type_averages = df_sim.groupby('type').agg({'averages':'mean'})
  beta_averages = beta_contrasts @ type_averages

  # pi >= 0.4/48 and |psi| <= 24 for any num_votes >= 1.
  # With lam=0.04, both one-step betting factors are >= 0.04.
  def eval(y, idx, pi, side = 1):
    type_idx = df_indices['type'][idx]
    beta_values = np.array([a[0] for a in beta_averages.values])
    psi = beta_values + beta_contrasts[:,type_idx] * (1 / num_per_arm) / pi * (y - df_sim.averages[idx])
    return (1 + side * lam * psi)

  e_processes_pos = np.ones(7)
  e_processes_neg = np.ones(7)
  e_processes = np.ones(7)
  maxima = e_processes.copy()

  def pull_idx(idx, pi):
    new_rating = np.random.choice(
      [0, 0.5, 1], size=num_votes,
      p=df_indices[['p1', 'p2', 'p3']].iloc[idx]
    ).mean()
    n_pulls = df_sim.loc[idx, 'pulls']
    # Maintain separate one-sided processes, then average to form the two-sided e-process.
    e_processes_pos[:7] *= eval(new_rating, idx, pi, side = 1)
    e_processes_neg[:7] *= eval(new_rating, idx, pi, side = -1)
    e_processes[:7] = (e_processes_pos + e_processes_neg) / 2
    maxima[:7] = np.maximum(maxima, e_processes)
    df_sim.loc[idx, 'averages'] = df_sim.loc[idx, 'averages'] * n_pulls / (n_pulls + 1) + new_rating / (n_pulls + 1)
    df_sim.loc[idx, 'pulls'] = df_sim.loc[idx, 'pulls'] + 1
    df_sim.loc[idx, 'ucbs'] = ucb(num_votes * df_sim.loc[idx,'pulls'], df_sim.loc[idx, 'averages'])
    type_averages[:8] = df_sim.groupby('type').agg({'averages':'mean'})
    beta_averages[:7] = beta_contrasts @ type_averages

  reject_e = False
  pulls_e = float('inf')
  e_arm = None
  reject_p = False
  pulls_p = float('inf')
  reject_pseudo_e = False
  pulls_pseudo_e = float('inf')
  reject_ep = False
  pulls_ep = float('inf')

  checkpoint_evals = {}
  np.random.seed(seed)
  for s in range(num_iter):


    pis = np.ones(n_arms) * epsilon / n_arms + np.array(df_sim.ucbs == df_sim.ucbs.max()) * (1 - epsilon) / np.sum(df_sim.ucbs == df_sim.ucbs.max())

    idx = np.random.choice(np.arange(n_arms), p = pis)
    pull = pull_idx(idx, pis[idx])


    if not reject_e:
      best_adj_e = np.max(e_dag(e_processes)[3:6])
      if best_adj_e > 1 / alpha:
        evals_adj = e_dag(e_processes)
        e_idx = np.argmax(evals_adj[3:6])
        pulls_e = s
        reject_e = True
        e_arm = e_idx


    if not reject_p:
      best_adj_p = np.min(p_dag(1 / maxima)[3:6])
      if best_adj_p < alpha:
        pvals_adj = p_dag(1 / maxima)
        p_idx = np.argmin(pvals_adj[3:6])
        pulls_p = s
        reject_p = True

    if not reject_pseudo_e:
      best_adj_pseudo_e = np.max(e_dag(maxima)[3:6])
      if best_adj_pseudo_e > 1 / alpha:
        pseudo_evals_adj = e_dag(maxima)
        pseudo_idx = np.argmax(pseudo_evals_adj[3:6])
        pulls_pseudo_e = s
        reject_pseudo_e = True

    if not reject_ep:
      best_adj_ep = np.min(p_dag(1 / e_processes)[3:6])
      if best_adj_ep < alpha:
        epvals_adj = p_dag(1 / e_processes)
        ep_idx = np.argmin(epvals_adj[3:6])
        pulls_ep = s
        reject_ep = True

    if checkpoints is not None and (s + 1) in checkpoints:
      checkpoint_evals[s + 1] = np.asarray(e_dag(e_processes)[:6]).copy()

  result = (df_sim, maxima, e_processes, beta_averages,
            pulls_p, pulls_e, pulls_pseudo_e, pulls_ep, e_arm)
  return (*result, checkpoint_evals) if checkpoints is not None else result

