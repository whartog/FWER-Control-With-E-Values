# Gaussian likelihood-ratio approximation for transformed ratings (0, 0.5, 1).
def fixed_sample_eval(y_bar, n_obs, mu_alt=.3, sigma=.5, mu_0=.25):
    return np.exp((mu_alt-mu_0)*y_bar*n_obs/sigma**2
                  -(mu_alt**2-mu_0**2)*n_obs/(2*sigma**2))

def compute_fixed_time_rates(n_obs, n_replications=REPLICATIONS, seed=0):
    np.random.seed(seed)
    out = np.zeros((n_replications, 4, 2))
    for rep in range(n_replications):
        samples = np.array([np.random.choice([1,2,3], size=n_obs, p=probs)
                            for probs in caption_probabilities])
        means = (samples.mean(axis=1)-1)/2
        e_values = fixed_sample_eval(means, n_obs)
        oracle_e_values = fixed_sample_eval(means, n_obs, mu_alt=oracle_alternatives)
        p_values = ttest_1samp(samples, 1.5, axis=1, alternative='greater').pvalue
        pseudo_e_values = 1/np.maximum(p_values, 1e-6)
        reject = [p_holm(p_values) <= ALPHA,
                  e_holm(e_values) >= 1/ALPHA,
                  e_holm(oracle_e_values) >= 1/ALPHA,
                  e_holm(pseudo_e_values) >= 1/CALIBRATED_ALPHA_50]
        for m, selection in enumerate(reject):
            out[rep,m,0] = np.any(selection[N_ALT:])
            out[rep,m,1] = np.mean(selection[:N_ALT])
    return out.mean(axis=0)

